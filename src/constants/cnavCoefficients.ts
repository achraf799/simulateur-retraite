export function getCnavRevaluationYear(liquidationYear: number): number | undefined {
  if (!Number.isInteger(liquidationYear) || liquidationYear < FIRST_REVALUATION_YEAR) return undefined;
  return Math.min(liquidationYear, LAST_REVALUATION_YEAR);
}

export function getCnavCoeff(year: number, liquidationYear = 2025): number {
  const revaluationYear = getCnavRevaluationYear(liquidationYear);
  if (revaluationYear === undefined) return 1;
  return COEFFICIENTS[year - FIRST_SALARY_YEAR]?.[revaluationYear - FIRST_REVALUATION_YEAR] ?? 1;
}
